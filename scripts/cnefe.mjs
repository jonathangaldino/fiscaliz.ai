#!/usr/bin/env node
/**
 * IBGE CNEFE (Censo 2022) addresses for one city. Open data, see docs/dados-ibge.md.
 *
 *   node scripts/cnefe.mjs download ["Apucarana, PR"]  # → data/cnefe/<code>_<NAME>.csv
 *   node scripts/cnefe.mjs build ["Apucarana, PR"]     # CSV → convex/cnefe/<code>.ts
 */
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const FTP =
  "https://ftp.ibge.gov.br/Cadastro_Nacional_de_Enderecos_para_Fins_Estatisticos/Censo_Demografico_2022/Arquivos_CNEFE/CSV/Municipio/";
const DATA_DIR = "data/cnefe";
const MODULE_DIR = "convex/cnefe";
// NV_GEO_COORD 1-3 are address coordinates; 4 (block face) and 5 (locality) are too coarse.
const ADDRESS_LEVELS = new Set(["1", "2", "3"]);

const plain = (text) =>
  text.normalize("NFD").replace(/[̀-ͯ]/g, "").toUpperCase().trim();

/** "Apucarana, PR" → { code: "4101408", uf: "PR" } via the IBGE localities API. */
async function findCity(arg) {
  const [name, uf] = arg.split(",").map((part) => part?.trim());
  if (!name || !/^[A-Za-z]{2}$/.test(uf ?? "")) throw new Error(`Expected "City, UF", got "${arg}"`);
  const response = await fetch(
    `https://servicodados.ibge.gov.br/api/v1/localidades/estados/${uf}/municipios`,
  );
  if (!response.ok) throw new Error(`IBGE localities HTTP ${response.status}`);
  const cities = await response.json();
  const city = cities.find((c) => plain(c.nome) === plain(name));
  if (!city) throw new Error(`No city "${name}" in ${uf.toUpperCase()}`);
  return { code: String(city.id), uf: uf.toUpperCase() };
}

async function links(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`IBGE FTP HTTP ${response.status} for ${url}`);
  return [...(await response.text()).matchAll(/href="([^"]+)"/g)].map((m) => m[1]);
}

async function download(city) {
  const ufDir = (await links(FTP)).find((href) => href.endsWith(`_${city.uf}/`));
  if (!ufDir) throw new Error(`No CNEFE folder for ${city.uf}`);
  const zipName = (await links(FTP + ufDir)).find((href) => href.startsWith(`${city.code}_`));
  if (!zipName) throw new Error(`No CNEFE file for ${city.code}`);
  const response = await fetch(FTP + ufDir + zipName);
  if (!response.ok) throw new Error(`IBGE FTP HTTP ${response.status} for ${zipName}`);

  const work = mkdtempSync(join(tmpdir(), "cnefe-"));
  writeFileSync(join(work, zipName), Buffer.from(await response.arrayBuffer()));
  execFileSync("unzip", ["-o", "-q", join(work, zipName), "-d", work]);
  const csv = readdirSync(work).find((file) => file.endsWith(".csv"));
  if (!csv) throw new Error(`${zipName} has no CSV`);
  mkdirSync(DATA_DIR, { recursive: true });
  renameSync(join(work, csv), join(DATA_DIR, csv));
  console.log(`${DATA_DIR}/${csv}`);
}

/** One row per street: parallel arrays of house numbers and coordinates, sorted by number. */
export function streetsFromCsv(text) {
  const [header, ...rows] = text.split(/\r?\n/);
  const col = Object.fromEntries(header.split(";").map((name, i) => [name, i]));
  const streets = new Map();
  for (const line of rows) {
    if (!line) continue;
    const r = line.split(";");
    const number = Number(r[col.NUM_ENDERECO]);
    if (!(number > 0) || !ADDRESS_LEVELS.has(r[col.NV_GEO_COORD])) continue;
    const name = [r[col.NOM_TIPO_SEGLOGR], r[col.NOM_TITULO_SEGLOGR], r[col.NOM_SEGLOGR]]
      .filter(Boolean)
      .join(" ");
    if (!streets.has(name)) streets.set(name, new Map());
    // Apartments repeat the number; the first coordinate is enough.
    if (!streets.get(name).has(number)) {
      streets.get(name).set(number, [Number(r[col.LATITUDE]), Number(r[col.LONGITUDE])]);
    }
  }
  return [...streets].map(([name, points]) => {
    const sorted = [...points].sort((a, b) => a[0] - b[0]);
    return {
      name,
      numbers: sorted.map(([n]) => n),
      lats: sorted.map(([, [lat]]) => lat),
      lngs: sorted.map(([, [, lng]]) => lng),
    };
  });
}

function csvFor(city) {
  const file = readdirSync(DATA_DIR).find((f) => f.startsWith(`${city.code}_`) && f.endsWith(".csv"));
  if (!file) throw new Error(`No CSV for ${city.code} in ${DATA_DIR}; run download first`);
  // IBGE ships the CSV in Latin-1.
  return readFileSync(join(DATA_DIR, file), "latin1");
}

/** Bundled into the Convex functions: no database read per lookup (ADR 0006). */
function build(city) {
  const streets = streetsFromCsv(csvFor(city));
  mkdirSync(MODULE_DIR, { recursive: true });
  const file = join(MODULE_DIR, `${city.code}.ts`);
  writeFileSync(
    file,
    `// Generated by scripts/cnefe.mjs from IBGE CNEFE 2022 (${city.code}). Do not edit.\n` +
      `import type { Street } from "../lib/streets";\n\n` +
      `export const STREETS: Street[] = ${JSON.stringify(streets)};\n`,
  );
  console.log(`${file}: ${streets.length} streets`);
}

if (import.meta.main) {
  const [command, cityArg = "Apucarana, PR"] = process.argv.slice(2);
  if (command === "download") await download(await findCity(cityArg));
  else if (command === "build") build(await findCity(cityArg));
  else {
    console.error('Usage: node scripts/cnefe.mjs download|build ["City, UF"]');
    process.exit(1);
  }
}
